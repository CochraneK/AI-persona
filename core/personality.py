def sample_ocean(primary_diagnosis_name: str,
                 comorbidity_names: list[str] | None = None,
                 rng: random.Random = random.Random()) -> dict[str, int]:
    """根据主诊断（及共病）采样 OCEAN 分数
    
    返回: {"N": int, "E": int, "O": int, "A": int, "C": int}
    """
    key = _get_diagnosis_key(primary_diagnosis_name)
    base_ranges = DIAGNOSIS_OCEAN_RANGES.get(key, DIAGNOSIS_OCEAN_RANGES["healthy"])

    # 初始化范围
    ranges = dict(base_ranges)

    # 共病影响：共病的范围压低/拉高
    for comorb in (comorbidity_names or []):
        ck = _get_diagnosis_key(comorb)
        cr = DIAGNOSIS_OCEAN_RANGES.get(ck)
        if cr:
            for dim in OCEAN_DIMENSIONS:
                lo = min(ranges[dim][0], cr[dim][0])
                hi = max(ranges[dim][1], cr[dim][1])
                # 共病扩展范围但不收缩
                ranges[dim] = (lo, hi)

    # 采样
    result = {}
    for dim in OCEAN_DIMENSIONS:
        lo, hi = ranges[dim]
        result[dim] = rng.randint(lo, hi)
    return result


def sample_tags_from_ocean(ocean: dict[str, int],
                            count: int = 3,
                            rng: random.Random = random.Random()) -> list[str]:
    """根据 OCEAN 分数采样性格标签
    
    每个维度：分 ≥ 6 → 高分簇采样，≤ 4 → 低分簇采样，5 → 随机选一极
    从选中的簇中各抽 1 个标签，再用剩余额度调剂。
    """
    candidates = []
    for dim in OCEAN_DIMENSIONS:
        score = ocean.get(dim, 5)
        if score >= 7:
            candidates.extend(PERSONALITY_TAGS[f"{dim}_high"]["tags"])
        elif score <= 3:
            candidates.extend(PERSONALITY_TAGS[f"{dim}_low"]["tags"])
        elif score >= 6:
            # 偏高一侧，但缓和
            candidates.extend(PERSONALITY_TAGS[f"{dim}_high"]["tags"][:3])
            candidates.extend(PERSONALITY_TAGS[f"{dim}_low"]["tags"][:2])
        elif score <= 4:
            candidates.extend(PERSONALITY_TAGS[f"{dim}_low"]["tags"][:3])
            candidates.extend(PERSONALITY_TAGS[f"{dim}_high"]["tags"][:2])
        else:
            # 居中：各取一些
            candidates.extend(PERSONALITY_TAGS[f"{dim}_high"]["tags"][:2])
            candidates.extend(PERSONALITY_TAGS[f"{dim}_low"]["tags"][:2])

    # 去重后随机选
    # sorted() 固定去重后的初始顺序：set 迭代序依赖 PYTHONHASHSEED（字符串
    # 哈希按进程随机化），直接 list(set(...)) 会让采样结果跨进程不可复现。
    # 排序后再用 rng.shuffle，结果只取决于 (candidates, rng 状态)，全确定。
    unique = sorted(set(candidates))
    rng.shuffle(unique)
    return unique[:min(count, len(unique))]


def describe_ocean(ocean: dict[str, int]) -> str:
    """将 OCEAN 分数转为自然语言描述"""
    parts = []
    for dim in OCEAN_DIMENSIONS:
        score = ocean[dim]
        low_desc, high_desc = OCEAN_LOW_HIGH[dim]
        if score >= 7:
            parts.append(f"{high_desc}({dim}={score})")
        elif score <= 3:
            parts.append(f"{low_desc}({dim}={score})")
        elif score >= 5:
            parts.append(f"偏{high_desc.split('/')[0]}({dim}={score})")
        else:
            parts.append(f"偏{low_desc.split('/')[0]}({dim}={score})")
    return "；".join(parts)


